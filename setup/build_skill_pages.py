#!/usr/bin/env python3
"""Render .claude/skills/<name>/{SKILL.md,references/*.md} as readable site pages under programs/.
Run from the repo root:  python3 setup/build_skill_pages.py
Generated files carry a 'generated: true' marker; edit the skills, not the pages."""
import re, shutil, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / ".claude" / "skills"
out = root / "programs"
SKIP = {"digest-program-source/references/digest-template"}   # template with placeholders, not knowledge
if out.exists(): shutil.rmtree(out)
out.mkdir()
def split_fm(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m: return {}, text
    fm = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        if _: fm[k.strip()] = v.strip()
    return fm, m.group(2)
def h1(body, default):
    m = re.search(r"^#\s+(.+)$", body, re.M)
    return m.group(1).strip() if m else default
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def raw(body): return "{% raw %}\n" + body.strip() + "\n{% endraw %}\n"
cards = []
for sd in sorted(p for p in src.iterdir() if (p / "SKILL.md").exists()):
    name = sd.name
    fm, body = split_fm((sd / "SKILL.md").read_text())
    refs = sorted((sd / "references").glob("*.md")) if (sd / "references").is_dir() else []
    pdir = out / name; pdir.mkdir()
    title = h1(body, name)
    desc = fm.get("description", "")
    page = f"---\ntitle: {q(name + ' — digest')}\ntype: reference\ntopic: Program digests\ngenerated: true\n---\n\n"
    page += f"> Type: reference · Claude Code skill `{name}` · [source on GitHub](https://github.com/Toki-bio/knowlege/tree/main/.claude/skills/{name})\n\n"
    if desc: page += f"**When to use:** {desc}\n\n---\n\n"
    page += raw(body)
    if refs:
        page += "\n## Reference pages\n\n"
        for r in refs:
            rfm, rbody = split_fm(r.read_text())
            page += f"- [{r.stem}]({r.stem}/) — {h1(rbody, r.stem)}\n"
    (pdir / "index.md").write_text(page)
    for r in refs:
        rfm, rbody = split_fm(r.read_text())
        t = h1(rbody, r.stem)
        rp = f"---\ntitle: {q(name + ': ' + t)}\ntype: reference\ngenerated: true\n---\n\n"
        rp += f"> Part of the [{name}](../) digest · [source](https://github.com/Toki-bio/knowlege/blob/main/.claude/skills/{name}/references/{r.name})\n\n"
        rp += raw(rbody)
        (pdir / f"{r.stem}.md").write_text(rp)
    cards.append((name, desc, len(refs)))
idx = "---\ntitle: Program digests\ntype: reference\ntopic: Program digests\ngenerated: true\n---\n\n"
idx += "> Type: reference\n\nReadable versions of the Claude Code skills in `.claude/skills/`: deep reads of programs (pinned upstream commit, architecture, control flow, I/O formats, pitfalls) plus a few working-method skills. Generated by `setup/build_skill_pages.py`; the skills themselves stay the source of truth.\n\n"
for name, desc, n in cards:
    short = desc if len(desc) <= 220 else desc[:220].rsplit(" ", 1)[0] + "…"
    cnt = f"{n} reference page{'s' if n != 1 else ''}" if n else "single page"
    idx += f"- **[{name}]({name}/)** ({cnt}) — {short}\n"
(out / "index.md").write_text(idx)
print(len(cards), "skills,", sum(c[2] for c in cards), "reference pages")
